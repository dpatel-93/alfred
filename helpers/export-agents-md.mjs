#!/usr/bin/env node
// Alfred charter export — emits AGENTS.md, the format Grok Build, Codex and most other terminal
// agents read natively. This is what lets a non-Claude host run Alfred's orchestration.
//
// Usage: node export-agents-md.mjs [outputPath]     (default: ./AGENTS.md)
//
// SINGLE SOURCE OF TRUTH: the charter is the home CLAUDE.md, included verbatim. Nothing is
// paraphrased here, because a hand-maintained second copy of the rules drifts from the first
// and then quietly contradicts it — which is worse than having no second copy at all.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const home = os.homedir();
const charterPath = path.join(home, 'CLAUDE.md');
const registryPath = path.join(home, '.claude', 'helpers', 'providers.json');
const outPath = path.resolve(process.argv[2] ?? 'AGENTS.md');

if (!fs.existsSync(charterPath)) {
  console.error(`error: no charter at ${charterPath}`);
  process.exit(1);
}

const charter = fs.readFileSync(charterPath, 'utf8');
const registry = Object.fromEntries(
  Object.entries(JSON.parse(fs.readFileSync(registryPath, 'utf8'))).filter(([k]) => !k.startsWith('_')),
);

// --- Provider table, generated so it cannot drift from the registry ---

const rows = Object.entries(registry).map(([id, s]) => {
  const gate = s.approval === 'ask-per-use' ? '**ask first, every use**' : 'no gate';
  return `| \`${id}\` | ${s.label} | ${s.specialism ?? '—'} | ${s.cost} | ${gate} |`;
});

// Route-for / never-route-for and output contracts are generated from the registry so the
// charter cannot drift from the thing that actually dispatches the work.
const specialisms = Object.entries(registry)
  .filter(([, s]) => s.routeFor || s.neverRouteFor || s.outputContract)
  .map(([id, s]) => {
    const lines = [`### \`${id}\` — ${s.specialism ?? s.label}`, ''];
    if (s.routeFor) lines.push('**Route here for:**', ...s.routeFor.map((r) => `- ${r}`), '');
    if (s.neverRouteFor) lines.push('**Never route here for:**', ...s.neverRouteFor.map((r) => `- ${r}`), '');
    if (s.outputContract) lines.push(`**Output contract:** ${s.outputContract}`, '');
    return lines.join('\n');
  })
  .join('\n');

const header = `<!-- GENERATED by helpers/export-agents-md.mjs — do not edit by hand.
     Source of truth: ~/CLAUDE.md and ~/.claude/helpers/providers.json
     Regenerate with: node ~/.claude/helpers/export-agents-md.mjs -->

# Alfred — Agent Charter

This file exists so that **any** terminal coding agent can run Alfred's orchestration, not only
Claude Code. Grok Build, Codex and most other agents read \`AGENTS.md\` natively; this is that file.

## How to read this

Alfred organises work as an **org chart of roles** — c-suite, vp, manager, employee, intern. The
roles are jobs, not vendors. Whichever model you are, you are filling one of those roles right now,
and the charter below tells you how that role behaves: what it delegates, what it verifies, and what
it must not decide alone.

Some of the charter names Claude Code features (the Agent tool, skills, hooks). Where your host has
no equivalent, **apply the intent, not the mechanism** — delegate however your host delegates, and
if it cannot delegate at all, do the work yourself but keep the verification obligations.

## Connected providers

| id | provider | specialism | cost | approval |
|---|---|---|---|---|
${rows.join('\n')}

**Route to a provider for its specialism, not to save tokens.** Cost is the tiebreak, never the
reason — a cheap answer from the wrong specialist is not a saving.

${specialisms}

- Discover what this machine can reach: \`node ~/.claude/helpers/provider-setup.mjs\`
- Dispatch to a provider: \`node ~/.claude/helpers/provider-run.mjs <id> "<prompt>" [--role manager]\`

**Approval is not optional.** A provider marked *ask first* requires the operator's explicit yes for
that specific call. Being signed in is not standing permission. This applies to you regardless of
which model you are.

---

`;

fs.writeFileSync(outPath, header + charter);
console.log(`wrote ${outPath} (${(header + charter).length} bytes, ${Object.keys(registry).length} providers)`);
